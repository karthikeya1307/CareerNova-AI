"""Alembic migration tests (run against the *_test database only).

The test database is built from the models (the full current schema),
stamped at head, compared with the models, then the real migration
scripts are rolled back to before Phase 1 and re-applied step by step.
"""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect

from backend import database
from backend.models import Base

PROJECT_ROOT = Path(__file__).resolve().parents[1]
PRE_PHASE_1 = "5d38d7da1031"
PHASE_1 = "a1c4e2b7d9f0"
PHASE_2 = "b7e3d1f4a2c8"
PHASE_3 = "c4f8a9e2b6d1"


@pytest.fixture
def alembic_config():
    assert database.engine.url.database.endswith("_test")
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    return config


def columns(table):
    return {c["name"] for c in inspect(database.engine).get_columns(table)}


def indexes(table):
    return {i["name"] for i in inspect(database.engine).get_indexes(table)}


def assert_no_drift(config):
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover
        pytest.fail(f"Model/migration drift detected: {exc}")


def test_single_linear_head(alembic_config):
    script = ScriptDirectory.from_config(alembic_config)
    assert script.get_heads() == [PHASE_3]
    assert script.get_revision(PHASE_3).down_revision == PHASE_2
    assert script.get_revision(PHASE_2).down_revision == PHASE_1
    assert script.get_revision(PHASE_1).down_revision == PRE_PHASE_1


def test_migrations_round_trip_without_drift(alembic_config):
    Base.metadata.drop_all(bind=database.engine)
    Base.metadata.create_all(bind=database.engine)
    command.stamp(alembic_config, "head")
    assert_no_drift(alembic_config)

    # Roll back Phase 3, Phase 2 and Phase 1.
    command.downgrade(alembic_config, PRE_PHASE_1)
    assert "run_id" not in columns("match_results")
    assert "uq_skills_name_lower" not in indexes("skills")
    assert "external_id" not in columns("internships")
    assert "content" not in columns("knowledge_documents")

    # Re-apply Phase 1 only.
    command.upgrade(alembic_config, PHASE_1)
    assert "uq_skills_name_lower" in indexes("skills")
    assert "external_id" not in columns("internships")

    # Re-apply Phase 2.
    command.upgrade(alembic_config, PHASE_2)
    assert {"external_id", "domain", "work_mode", "duration_weeks",
            "stipend_per_month", "stipend_currency", "min_education",
            "source"} <= columns("internships")
    assert {"content", "embedding_model", "error_message"} <= columns(
        "knowledge_documents"
    )
    assert "ix_internships_domain" in indexes("internships")
    assert "run_id" not in columns("match_results")

    # Re-apply Phase 3.
    command.upgrade(alembic_config, PHASE_3)
    assert {"run_id", "rank", "label", "algorithm_version", "skill_score",
            "semantic_score", "education_score", "location_score",
            "required_skill_coverage", "data_completeness", "breakdown"} <= columns("match_results")
    assert {"ix_match_results_run_id", "ix_match_results_resume_created"} <= indexes("match_results")

    assert_no_drift(alembic_config)
