"""Skill progress (Not Started / Learning / Practiced / Completed) and the per-job learning roadmap.

Progress is stored per (student, skill) in ``skill_progress``, so learning Docker counts for every
job that needs Docker. Setting progress also moves the student's current skill-gap recommendations
for that skill to the matching recommendation status (not_started -> pending, learning/practiced ->
in_progress, completed -> completed), so both views agree.

The roadmap for one job lists the job's missing and partial skills in a learning order that
respects prerequisites, each with: importance, why the job needs it, current evidence on the
resume, learning topics and estimated hours (learning_plans.json), an official documentation link
when one is curated, interview questions from the question bank, a practice project and the
student's progress status. Nothing is generated by an AI and no link is invented.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from backend.models import Internship, Skill, SkillGapRecommendation, SkillProgress
from backend.services.learning_plans import learning_order, plan_for
from backend.services.question_bank import questions_for_skill
from backend.services.skill_gap import assess_internship, update_status
from backend.services.skill_normalizer import normalize_skill

STATUSES = ("not_started", "learning", "practiced", "completed")
LABELS = {"not_started": "Not Started", "learning": "Learning", "practiced": "Practiced", "completed": "Completed"}
TO_RECOMMENDATION = {"not_started": "pending", "learning": "in_progress", "practiced": "in_progress",
                     "completed": "completed"}
TRACKS_PATH = Path(__file__).resolve().parents[1] / "data" / "career_tracks.json"


@lru_cache(maxsize=1)
def official_resources() -> dict[str, dict]:
    return json.loads(TRACKS_PATH.read_text(encoding="utf-8"))["official_resources"]


class UnknownSkillError(ValueError):
    pass


def resolve_skill(db: Session, name: str) -> Skill:
    """The catalogue skill for a name (case-insensitive, aliases normalised)."""
    raw = (name or "").strip()
    if not raw:
        raise UnknownSkillError("Skill name is required.")
    normalized = normalize_skill(raw)
    candidates = [raw] + ([normalized.name] if normalized is not None else [])
    for candidate in candidates:
        skill = db.scalar(select(Skill).where(func.lower(Skill.name) == candidate.lower()))
        if skill is not None:
            return skill
    raise UnknownSkillError(f"'{raw}' is not in the skill catalogue.")


def statuses_for(db: Session, user_id: int) -> dict[str, dict]:
    rows = db.execute(select(SkillProgress, Skill).join(Skill, Skill.skill_id == SkillProgress.skill_id)
                      .where(SkillProgress.user_id == user_id)).all()
    return {skill.name: {"status": progress.status, "updated_at": progress.updated_at} for progress, skill in rows}


def set_status(db: Session, user_id: int, skill: Skill, status: str) -> SkillProgress:
    if status not in STATUSES:
        raise ValueError(f"status must be one of {', '.join(STATUSES)}")
    progress = db.scalar(select(SkillProgress).where(SkillProgress.user_id == user_id,
                                                     SkillProgress.skill_id == skill.skill_id))
    if progress is None:
        progress = SkillProgress(user_id=user_id, skill_id=skill.skill_id, status=status)
        db.add(progress)
    else:
        progress.status = status
    for rec in db.scalars(select(SkillGapRecommendation).where(
            SkillGapRecommendation.user_id == user_id, SkillGapRecommendation.skill_id == skill.skill_id,
            SkillGapRecommendation.is_current.is_(True), SkillGapRecommendation.status != "dismissed")):
        update_status(rec, TO_RECOMMENDATION[status])
    db.flush()
    return progress


def _why(skill: str, importance: str, internship: Internship) -> str:
    base = (f"{internship.title} at {internship.company} lists {skill} as a "
            f"{'required' if importance == 'required' else 'preferred'} skill.")
    for sentence in re.split(r"(?<=[.!?])\s+", internship.description or ""):
        if re.search(rf"(?<![\w+#]){re.escape(skill)}(?![\w+#])", sentence, re.IGNORECASE):
            return f"{base} The posting says: “{sentence.strip()[:240]}”"
    return base


def _project(skill: str, internship: Internship) -> str:
    area = internship.domain or "this field"
    return (f"Build a small {area} project that uses {skill} for a task similar to this role "
            f"({internship.title}), publish the code and describe the result on your resume.")


def roadmap(db: Session, user_id: int, candidate_skills: list[str], internship: Internship,
            skill_match: int | None) -> dict[str, Any]:
    progress = statuses_for(db, user_id)
    assessments = assess_internship(candidate_skills, internship)
    gaps = {a.skill: a for a in assessments if a.status in ("missing", "partial")}
    known = {a.skill for a in assessments if a.status == "matched"} | set(candidate_skills)
    ordered = learning_order(list(gaps), known)
    resources = official_resources()
    steps = []
    for position, name in enumerate(ordered, start=1):
        a = gaps[name]
        plan = plan_for(name)
        questions = [q["question"] for q in questions_for_skill(name)[:3]]
        state = progress.get(name, {}).get("status", "not_started")
        steps.append({
            "step": position,
            "skill": name,
            "importance": a.importance,
            "gap": a.status,
            "why": _why(name, a.importance, internship),
            "evidence": ([f"You have related skills: {', '.join(r['skill'] for r in a.related)}."] if a.related
                         else ["Not on your resume yet."]),
            "learning": {"level": plan.get("level"), "estimated_hours": plan.get("estimated_hours"),
                         "prerequisites": plan.get("prerequisites", []), "topics": plan.get("topics", []),
                         "curated": plan.get("curated", False)},
            "resource": resources.get(name),
            "interview_questions": questions,
            "project": _project(name, internship),
            "status": state,
            "status_label": LABELS[state],
        })
    done = sum(1 for s in steps if s["status"] == "completed")
    return {
        "internship_id": internship.internship_id,
        "title": internship.title,
        "company": internship.company,
        "skill_match": skill_match,
        "have": sorted(a.skill for a in assessments if a.status == "matched"),
        "steps": steps,
        "progress": {"total": len(steps), "completed": done,
                     "by_status": {s: sum(1 for x in steps if x["status"] == s) for s in STATUSES},
                     "percent": round(100 * done / len(steps)) if steps else 100},
    }
