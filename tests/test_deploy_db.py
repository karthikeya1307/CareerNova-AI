"""Deploy-time database initialisation (backend/deploy_db.py).

Each test creates its OWN empty database named ``career_companion_deploy_<random>_test`` (never an
existing one) and removes only that database afterwards. This mirrors a brand-new Neon database.
"""

import uuid

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.orm import sessionmaker

from backend import database, deploy_db
from backend.models import Base

HEAD = ScriptDirectory.from_config(deploy_db.alembic_config()).get_current_head()


@pytest.fixture
def fresh_db(monkeypatch):
    """A brand-new empty database; the app's engine/session point at it for the test."""
    name = f"career_companion_deploy_{uuid.uuid4().hex[:8]}_test"
    admin = create_engine(database.DATABASE_URL.set(database="postgres"), isolation_level="AUTOCOMMIT")
    try:
        with admin.connect() as c:
            c.execute(text(f'CREATE DATABASE "{name}"'))
    except Exception as exc:  # pragma: no cover - environments without CREATEDB
        admin.dispose()
        pytest.skip(f"cannot create a scratch database here ({type(exc).__name__})")
    engine = create_engine(database.DATABASE_URL.set(database=name))
    monkeypatch.setattr(database, "engine", engine)
    monkeypatch.setattr(database, "SessionLocal", sessionmaker(bind=engine, autoflush=False, expire_on_commit=False))
    try:
        yield engine
    finally:
        engine.dispose()
        with admin.connect() as c:                       # only the database this fixture created
            assert name.startswith("career_companion_deploy_") and name.endswith("_test")
            c.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin.dispose()


def tables(engine):
    return set(inspect(engine).get_table_names())


def revision(engine):
    with engine.connect() as c:
        return c.execute(text("SELECT version_num FROM alembic_version")).scalar()


def assert_no_drift(engine):
    config = deploy_db.alembic_config()
    with engine.connect() as c:
        config.attributes["connection"] = c
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - shows the drift
            pytest.fail(f"schema differs from the models: {exc}")


def test_check_mode_changes_nothing_on_an_empty_database(fresh_db, capsys):
    assert deploy_db.main(["--check"]) == 0
    assert "state=fresh" in capsys.readouterr().out
    assert tables(fresh_db) == set()


def test_fresh_database_is_created_stamped_and_seeded(fresh_db, capsys):
    assert deploy_db.main(["--seed-if-empty"]) == 0
    out = capsys.readouterr().out
    assert "Fresh database" in out and f"revision {HEAD}" in out and "seeded 180 curated internships" in out
    assert tables(fresh_db) == set(Base.metadata.tables) | {"alembic_version"}
    assert revision(fresh_db) == HEAD
    assert_no_drift(fresh_db)
    with fresh_db.connect() as c:                     # special objects that only migrations used to add
        indexes = {r[0] for r in c.execute(text("SELECT indexname FROM pg_indexes WHERE schemaname='public'"))}
        checks = {r[0] for r in c.execute(text("SELECT conname FROM pg_constraint WHERE contype='c'"))}
        assert c.execute(text("SELECT count(*) FROM internships WHERE is_active")).scalar() == 180
    assert {"uq_skills_name_lower", "uq_users_single_super_admin"} <= indexes
    assert {"ck_users_role", "ck_applications_status"} <= checks

    # Second deploy: normal Alembic path, nothing re-seeded or recreated.
    assert deploy_db.main(["--seed-if-empty"]) == 0
    out = capsys.readouterr().out
    assert "state=managed" in out and "applying Alembic migrations" in out and "seeding skipped" in out
    assert revision(fresh_db) == HEAD


def test_leftover_version_row_from_a_failed_attempt_is_treated_as_fresh(fresh_db, capsys):
    # What a failed "alembic upgrade head" on an empty database can leave behind.
    with fresh_db.begin() as c:
        c.execute(text("CREATE TABLE alembic_version (version_num VARCHAR(32) PRIMARY KEY)"))
        c.execute(text("INSERT INTO alembic_version VALUES ('9c59adb5cc64')"))
    assert deploy_db.main([]) == 0
    assert "state=fresh" in capsys.readouterr().out
    assert revision(fresh_db) == HEAD and "users" in tables(fresh_db)


def test_tables_without_alembic_version_stop_without_changes(fresh_db, capsys):
    with fresh_db.begin() as c:
        c.execute(text("CREATE TABLE users (user_id serial PRIMARY KEY)"))
    assert deploy_db.main([]) == 1
    assert "STOP" in capsys.readouterr().out
    assert tables(fresh_db) == {"users"}                # nothing created, nothing dropped
