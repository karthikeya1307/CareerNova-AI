"""Alembic migration tests (run against the *_test database only).

The test database schema is built from the models before Phase 1's
migration, then the real migration scripts are applied, rolled back and
re-applied, and finally compared with the models.
"""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, text

from backend import database

PROJECT_ROOT = Path(__file__).resolve().parents[1]
PHASE_1_REVISION = "a1c4e2b7d9f0"
PRE_PHASE_1_REVISION = "5d38d7da1031"


@pytest.fixture
def alembic_config():
    assert database.engine.url.database.endswith("_test")
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    return config


def skill_index_names():
    return {ix["name"] for ix in inspect(database.engine).get_indexes("skills")}


def test_single_linear_head(alembic_config):
    script = ScriptDirectory.from_config(alembic_config)
    assert script.get_heads() == [PHASE_1_REVISION]


def test_phase_1_migration_upgrade_downgrade_and_no_drift(alembic_config):
    # Start from the pre-Phase-1 state: same schema without the index.
    with database.engine.begin() as connection:
        connection.execute(text("DROP INDEX IF EXISTS uq_skills_name_lower"))
    command.stamp(alembic_config, PRE_PHASE_1_REVISION)
    assert "uq_skills_name_lower" not in skill_index_names()

    command.upgrade(alembic_config, "head")
    assert "uq_skills_name_lower" in skill_index_names()

    command.downgrade(alembic_config, PRE_PHASE_1_REVISION)
    assert "uq_skills_name_lower" not in skill_index_names()

    command.upgrade(alembic_config, "head")
    assert "uq_skills_name_lower" in skill_index_names()

    # Models and migrated database must match exactly.
    try:
        command.check(alembic_config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover
        pytest.fail(f"Model/migration drift detected: {exc}")
