"""Alembic migration tests (run against the *_test database only).

The test database is built from the models (the full current schema),
stamped at head, compared with the models, then the real migration
scripts are rolled back to before Phase 1 and re-applied step by step.
"""

import argparse
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, text

from backend import database
from backend.models import Base

PROJECT_ROOT = Path(__file__).resolve().parents[1]
PRE_PHASE_1 = "5d38d7da1031"
PHASE_1 = "a1c4e2b7d9f0"
PHASE_2 = "b7e3d1f4a2c8"
PHASE_3 = "c4f8a9e2b6d1"
PHASE_4 = "d5a1c7e3f9b2"
PHASE_5 = "e7b2d4f6a8c1"
PHASE_6 = "f3c9e1a5b7d2"
PHASE_7 = "a9d3f6b2c8e4"


@pytest.fixture
def alembic_config():
    assert database.engine.url.database.endswith("_test")
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    return config


def columns(table):
    return {c["name"] for c in inspect(database.engine).get_columns(table)}


def indexes(table):
    return {i["name"] for i in inspect(database.engine).get_indexes(table)}


def assert_no_drift(config):
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover
        pytest.fail(f"Model/migration drift detected: {exc}")


def test_single_linear_head(alembic_config):
    script = ScriptDirectory.from_config(alembic_config)
    assert script.get_heads() == [PHASE_7]
    assert script.get_revision(PHASE_7).down_revision == PHASE_6
    assert script.get_revision(PHASE_6).down_revision == PHASE_5
    assert script.get_revision(PHASE_5).down_revision == PHASE_4
    assert script.get_revision(PHASE_4).down_revision == PHASE_3
    assert script.get_revision(PHASE_3).down_revision == PHASE_2
    assert script.get_revision(PHASE_2).down_revision == PHASE_1
    assert script.get_revision(PHASE_1).down_revision == PRE_PHASE_1


def test_migrations_round_trip_without_drift(alembic_config):
    Base.metadata.drop_all(bind=database.engine)
    Base.metadata.create_all(bind=database.engine)
    command.stamp(alembic_config, "head")
    assert_no_drift(alembic_config)

    # Roll back Phase 4, Phase 3, Phase 2 and Phase 1.
    command.downgrade(alembic_config, PRE_PHASE_1)
    assert "run_id" not in columns("match_results")
    assert "resume_id" not in columns("skill_gap_recommendations")
    assert "uq_skills_name_lower" not in indexes("skills")
    assert "external_id" not in columns("internships")
    assert "content" not in columns("knowledge_documents")

    # Re-apply Phase 1 only.
    command.upgrade(alembic_config, PHASE_1)
    assert "uq_skills_name_lower" in indexes("skills")
    assert "external_id" not in columns("internships")

    # Re-apply Phase 2.
    command.upgrade(alembic_config, PHASE_2)
    assert {"external_id", "domain", "work_mode", "duration_weeks",
            "stipend_per_month", "stipend_currency", "min_education",
            "source"} <= columns("internships")
    assert {"content", "embedding_model", "error_message"} <= columns(
        "knowledge_documents"
    )
    assert "ix_internships_domain" in indexes("internships")
    assert "run_id" not in columns("match_results")

    # Re-apply Phase 3.
    command.upgrade(alembic_config, PHASE_3)
    assert {"run_id", "rank", "label", "algorithm_version", "skill_score",
            "semantic_score", "education_score", "location_score",
            "required_skill_coverage", "data_completeness", "breakdown"} <= columns("match_results")
    assert {"ix_match_results_run_id", "ix_match_results_resume_created"} <= indexes("match_results")
    assert "resume_id" not in columns("skill_gap_recommendations")

    # Re-apply Phase 4.
    command.upgrade(alembic_config, PHASE_4)
    assert {"resume_id", "importance", "priority_score", "demand_count", "internship_ids",
            "related_skills", "learning_plan", "learning_plan_version", "source",
            "source_run_id", "is_current", "completed_via", "started_at", "completed_at",
            "updated_at"} <= columns("skill_gap_recommendations")
    assert {"ix_skill_gap_recommendations_resume_id", "ix_skill_gap_user_status"} <= indexes(
        "skill_gap_recommendations")

    # Phase 4 downgrade and upgrade again.
    command.downgrade(alembic_config, PHASE_3)
    assert "priority_score" not in columns("skill_gap_recommendations")
    command.upgrade(alembic_config, PHASE_4)
    assert "priority_score" in columns("skill_gap_recommendations")
    assert "content_json" not in columns("generated_documents")

    # Phase 5: upgrade, downgrade, upgrade again.
    command.upgrade(alembic_config, PHASE_5)
    assert {"content_json", "generation_method", "llm_provider", "llm_model", "fact_check",
            "ats_report", "options", "current_version", "updated_at"} <= columns("generated_documents")
    assert "generated_document_versions" in inspect(database.engine).get_table_names()
    command.downgrade(alembic_config, PHASE_4)
    assert "content_json" not in columns("generated_documents")
    assert "generated_document_versions" not in inspect(database.engine).get_table_names()
    command.upgrade(alembic_config, PHASE_5)
    assert "generated_document_versions" in inspect(database.engine).get_table_names()
    assert "interview_answers" not in inspect(database.engine).get_table_names()

    # Phase 6: upgrade, downgrade, upgrade again.
    command.upgrade(alembic_config, PHASE_6)
    assert {"resume_id", "mode", "question_mix", "answered_count", "summary"} <= columns("interview_sessions")
    assert {"category", "position", "key_points", "suggested_answer", "evaluation"} <= columns("interview_questions")
    assert "interview_answers" in inspect(database.engine).get_table_names()
    command.downgrade(alembic_config, PHASE_5)
    assert "mode" not in columns("interview_sessions")
    assert "interview_answers" not in inspect(database.engine).get_table_names()
    command.upgrade(alembic_config, PHASE_6)
    assert "interview_answers" in inspect(database.engine).get_table_names()
    assert "saved_internships" not in inspect(database.engine).get_table_names()

    # Phase 7: upgrade, downgrade, upgrade again.
    command.upgrade(alembic_config, PHASE_7)
    assert {"source", "company_name", "title", "deleted_at", "application_url_normalized",
            "external_reference"} <= columns("applications")
    assert {"saved_internships", "application_status_history", "application_interviews",
            "application_reminders", "application_activity"} <= set(inspect(database.engine).get_table_names())
    command.downgrade(alembic_config, PHASE_6)
    assert "source" not in columns("applications")
    assert "saved_internships" not in inspect(database.engine).get_table_names()
    command.upgrade(alembic_config, "head")
    assert "application_activity" in inspect(database.engine).get_table_names()

    assert_no_drift(alembic_config)


def seed_phase6_rows(statuses):
    with database.engine.begin() as conn:
        conn.execute(text("INSERT INTO users (first_name, last_name, email, password_hash, is_verified) "
                          "VALUES ('T', 'U', 'migration@example.com', 'x', true)"))
        conn.execute(text("INSERT INTO internships (title, company, source, is_active, stipend_currency, work_mode) "
                          "VALUES ('Backend Intern', 'Nimbus', 'manual', true, 'INR', 'Remote'), "
                          "('Data Intern', 'Orbit', 'manual', true, 'INR', NULL), "
                          "('QA Intern', 'Kite', 'manual', true, 'INR', 'Onsite')"))
        user_id = conn.execute(text("SELECT user_id FROM users")).scalar()
        internships = conn.execute(text("SELECT internship_id FROM internships ORDER BY 1")).scalars().all()
        for internship_id, status in zip(internships, statuses):
            conn.execute(text("INSERT INTO applications (user_id, internship_id, status) VALUES (:u, :i, :s)"),
                         {"u": user_id, "i": internship_id, "s": status})


def fresh_phase6(alembic_config):
    Base.metadata.drop_all(bind=database.engine)
    Base.metadata.create_all(bind=database.engine)
    command.stamp(alembic_config, "head")
    command.downgrade(alembic_config, PHASE_6)


def test_phase7_migrates_legacy_lowercase_statuses(alembic_config):
    fresh_phase6(alembic_config)
    seed_phase6_rows([" Applied ", "interviewing", "saved"])
    command.upgrade(alembic_config, PHASE_7)
    with database.engine.connect() as conn:
        rows = conn.execute(text("SELECT status, source, company_name, title, work_mode FROM applications "
                                 "ORDER BY application_id")).all()
        history = conn.execute(text("SELECT to_status, change_type FROM application_status_history "
                                    "ORDER BY application_id")).all()
    assert [r.status for r in rows] == ["APPLIED", "INTERVIEW_SCHEDULED", "SAVED"]
    assert [(r.source, r.company_name, r.title, r.work_mode) for r in rows][0] == (
        "internal", "Nimbus", "Backend Intern", "Remote")
    assert history == [("APPLIED", "migrated"), ("INTERVIEW_SCHEDULED", "migrated"), ("SAVED", "migrated")]
    assert_no_drift(alembic_config)
    # Legacy rows only: the downgrade is allowed and restores lowercase statuses.
    command.downgrade(alembic_config, PHASE_6)
    with database.engine.connect() as conn:
        assert conn.execute(text("SELECT status FROM applications ORDER BY application_id")).scalars().all() == [
            "applied", "interview_scheduled", "saved"]
    command.upgrade(alembic_config, "head")


def test_phase7_backfills_application_dates_for_legacy_submitted_rows(alembic_config):
    fresh_phase6(alembic_config)
    seed_phase6_rows(["selected", "withdrawn", "saved"])
    with database.engine.begin() as conn:
        conn.execute(text("UPDATE applications SET applied_at = NULL, updated_at = '2026-10-05T10:00:00+05:30'"))
    command.upgrade(alembic_config, PHASE_7)
    with database.engine.connect() as conn:
        rows = conn.execute(text("SELECT status, applied_at FROM applications ORDER BY application_id")).all()
    assert rows[0].status == "SELECTED" and rows[0].applied_at is not None
    assert rows[0].applied_at.isoformat().startswith("2026-10-05")
    assert rows[1].status == "WITHDRAWN" and rows[1].applied_at is None      # may never have applied
    assert rows[2].status == "SAVED" and rows[2].applied_at is None
    command.downgrade(alembic_config, PHASE_6)                               # legacy rows only: allowed
    command.upgrade(alembic_config, "head")


def test_phase7_upgrade_refuses_unknown_statuses(alembic_config):
    fresh_phase6(alembic_config)
    seed_phase6_rows(["applied", "maybe later"])
    with pytest.raises(RuntimeError, match="unrecognised status values 'maybe later'"):
        command.upgrade(alembic_config, PHASE_7)
    with database.engine.connect() as conn:
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar() == PHASE_6
        assert conn.execute(text("SELECT status FROM applications ORDER BY 1")).scalars().all() == [
            "applied", "maybe later"]
    with database.engine.begin() as conn:
        conn.execute(text("DELETE FROM applications"))
    command.upgrade(alembic_config, "head")


def test_phase7_downgrade_protects_data_and_override_is_scoped(alembic_config):
    fresh_phase6(alembic_config)
    seed_phase6_rows(["applied"])
    command.upgrade(alembic_config, PHASE_7)
    with database.engine.begin() as conn:
        user_id = conn.execute(text("SELECT user_id FROM users")).scalar()
        internship_id = conn.execute(text("SELECT min(internship_id) FROM internships")).scalar()
        conn.execute(text("INSERT INTO applications (user_id, source, company_name, company_key, title, status) "
                          "VALUES (:u, 'external', 'Acme', 'acme', 'SRE Intern', 'APPLIED')"), {"u": user_id})
        conn.execute(text("INSERT INTO saved_internships (user_id, internship_id) VALUES (:u, :i)"),
                     {"u": user_id, "i": internship_id})
        conn.execute(text("INSERT INTO resumes (user_id, filename, file_path, file_type, status) "
                          "VALUES (:u, 'cv.pdf', 'uploads/x.pdf', 'pdf', 'uploaded')"), {"u": user_id})

    with pytest.raises(RuntimeError, match="Refusing to downgrade Phase 7"):
        command.downgrade(alembic_config, PHASE_6)
    with database.engine.connect() as conn:
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar() == PHASE_7
        assert conn.execute(text("SELECT count(*) FROM applications")).scalar() == 2
        assert conn.execute(text("SELECT count(*) FROM saved_internships")).scalar() == 1

    alembic_config.cmd_opts = argparse.Namespace(x=["phase7_allow_data_loss=true"])
    try:
        command.downgrade(alembic_config, PHASE_6)
    finally:
        alembic_config.cmd_opts = None
    with database.engine.connect() as conn:
        # Only Phase 7 data was removed: the legacy application, user, internships and resume remain.
        assert conn.execute(text("SELECT status FROM applications")).scalars().all() == ["applied"]
        assert conn.execute(text("SELECT count(*) FROM users")).scalar() == 1
        assert conn.execute(text("SELECT count(*) FROM internships")).scalar() == 3
        assert conn.execute(text("SELECT count(*) FROM resumes")).scalar() == 1
    command.upgrade(alembic_config, "head")
    assert_no_drift(alembic_config)
